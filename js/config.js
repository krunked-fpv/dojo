export function getSpriteUrls(id, back = false, shiny = false) {
  const dir = `${back ? 'back/' : ''}${shiny ? 'shiny/' : ''}`;
  return {
    animated: `https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/versions/generation-v/black-white/animated/${dir}${id}.gif`,
    static: `https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/${dir}${id}.png`,
  };
}

function hasPositiveCatchCount(count) {
  return count === true || Number(count) > 0;
}

function getCaughtEntries(profile) {
  return Object.entries(profile?.pokedex?.caught || {}).filter(([, count]) => hasPositiveCatchCount(count));
}

